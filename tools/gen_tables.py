"""Generate app/engine/tables.c: fixed-point lookup tables for the drum engine.
Run: python3 tools/gen_tables.py > app/engine/tables.c"""
import math

RATE = 44100
BLOCK = 128


def rows(values, per=8, fmt="{}"):
    out = []
    for i in range(0, len(values), per):
        out.append("    " + ", ".join(fmt.format(v) for v in values[i:i + per]) + ",")
    return "\n".join(out)


sine = [round(32767 * math.sin(2 * math.pi * i / 256)) for i in range(257)]

# Pitch: 128 steps from 20 Hz to 2 kHz, exponential; 32-bit phase increments.
tune_hz = [20 * (100 ** (i / 127)) for i in range(128)]
tune = [round(f / RATE * 2 ** 32) for f in tune_hz]

# Decay: 128 times from 3 ms to 3 s (time to -60 dB), per-sample factor Q30.
decay_s = [0.003 * (1000 ** (i / 127)) for i in range(128)]
decay = [min(round((10 ** (-3 / (t * RATE))) * 2 ** 30), 2 ** 30 - 1) for t in decay_s]

# FM ratios (Q8): a mix of harmonic and inharmonic (metallic) values.
ratios = [0.5, 1.0, 1.41, 1.5, 2.0, 2.76, 3.0, 3.5, 4.0, 5.19, 5.4, 6.0, 7.0, 8.0, 9.42, 11.0]
ratio_q8 = [round(r * 256) for r in ratios]

print("/* SPDX-License-Identifier: MIT */")
print("/* Generated by tools/gen_tables.py. Do not edit. */")
print('#include "tables.h"\n')
print("/* In RAM (FM1_AUDIO_DATA): the audio interrupt may run while flash is busy. */")
print("/* sin(2 pi i / 256) in Q15, one guard entry for interpolation. */")
print("int16_t table_sine[257] FM1_AUDIO_DATA = {\n" + rows(sine) + "\n};\n")
print("/* 20 Hz .. 2 kHz exponential, as 32-bit phase increments at 44.1 kHz. */")
print("uint32_t table_tune[128] FM1_AUDIO_DATA = {\n" + rows(tune, 6) + "\n};\n")
print("/* Envelope factor per sample, Q30: 3 ms .. 3 s to -60 dB. */")
print("uint32_t table_decay[128] FM1_AUDIO_DATA = {\n" + rows(decay, 6) + "\n};\n")
print("/* FM modulator ratios, Q8. */")
print("uint16_t table_ratio[16] FM1_AUDIO_DATA = {\n" + rows(ratio_q8) + "\n};")
