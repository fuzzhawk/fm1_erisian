"""Generate mavis/engine/mtables.c: fixed-point tables for the MAVIS engines.
Run: python3 tools/gen_mavis_tables.py > mavis/engine/mtables.c"""
import math

RATE = 44100


def rows(values, per=8):
    return "\n".join("    " + ", ".join(str(v) for v in values[i:i + per]) + ","
                     for i in range(0, len(values), per))


sine = [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)]
note_hz = [440 * 2 ** ((n - 69) / 12) for n in range(128)]
note_inc = [min(round(f / RATE * 2 ** 32), 2 ** 31) for f in note_hz]
note_period = [min(round(RATE / f * 65536), 2 ** 32 - 1) for f in note_hz]
semi_up = [round(2 ** (i / 256 / 12) * 65536) for i in range(257)]       # Q16
semi_down = [round(2 ** (-i / 256 / 12) * 65536) for i in range(257)]    # Q16
exp2_neg = [round(2 ** (-i / 256) * 65536) for i in range(257)]          # Q16

print("/* SPDX-License-Identifier: MIT */")
print("/* Generated by tools/gen_mavis_tables.py. Do not edit. */")
print('#include "engine/mtables.h"\n')
print("/* In RAM (FM1_AUDIO_DATA): read by the audio interrupt. */")
print("/* sin(2 pi i / 1024), Q15, one guard entry. */")
print("int16_t mt_sine[1025] FM1_AUDIO_DATA = {\n" + rows(sine, 10) + "\n};\n")
print("/* MIDI note: 32-bit phase increment at 44.1 kHz. */")
print("uint32_t mt_note_inc[128] FM1_AUDIO_DATA = {\n" + rows(note_inc, 6) + "\n};\n")
print("/* MIDI note: period in samples, Q16. */")
print("uint32_t mt_note_period[128] FM1_AUDIO_DATA = {\n" + rows(note_period, 6) + "\n};\n")
print("/* 2^(i/256/12), Q16: fractions of a semitone up. */")
print("uint32_t mt_semi_up[257] FM1_AUDIO_DATA = {\n" + rows(semi_up, 8) + "\n};\n")
print("/* 2^(-i/256/12), Q16: fractions of a semitone down. */")
print("uint32_t mt_semi_down[257] FM1_AUDIO_DATA = {\n" + rows(semi_down, 8) + "\n};\n")
print("/* 2^(-i/256), Q16: gain from a log2 attenuation fraction. */")
print("uint32_t mt_exp2_neg[257] FM1_AUDIO_DATA = {\n" + rows(exp2_neg, 8) + "\n};")
